type hotStateSpec struct {
	table     customTableSpec
	baseName  string
	keyType   string
	entryType string
	cacheType string
	batchType string
}

func generateHotStateGo(tables []customTableSpec, events []eventSpec) ([]byte, error) {
	var b bytes.Buffer
	specs := hotStateSpecs(tables)

	b.WriteString(`// Code generated by sqd-go codegen; DO NOT EDIT.

package generated

`)
	renderHotStateImports(&b, tables, events)

	b.WriteString("const DefaultClockCacheCapacity uint64 = 100000\n\n")
	for _, spec := range specs {
		if !spec.table.IsEvent {
			renderHotStateEntity(&b, spec.table)
		}
		renderClockKey(&b, spec)
		renderClockCache(&b, spec)
		if !spec.table.IsEvent {
			renderCustomBatch(&b, spec)
			renderClockRecover(&b, spec)
		}
		renderBatchResolver(&b, spec)
	}
	renderHotStateType(&b, specs)
	renderHotStateHelpers(&b, tables, events)

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format source: %w", err)
	}
	return formatted, nil
}

func renderHotStateImports(b *bytes.Buffer, tables []customTableSpec, events []eventSpec) {
	imports := map[string]string{
		`"context"`:                                            "",
		`"fmt"`:                                                "",
		`"strings"`:                                            "",
		`"sync"`:                                               "",
		`"sync/atomic"`:                                        "",
		`"github.com/ClickHouse/ch-go"`:                        "",
		`"github.com/ClickHouse/ch-go/proto"`:                  "",
		`"github.com/franz101/sqd-go/internal/coldcache"`:      "",
	}
	if customTablesUseDecimal(tables) {
		imports[`"encoding/binary"`] = ""
		imports[`"math/big"`] = ""
	}
	if customTablesUseColdCache(tables) {
		// Cold tier (Pebble) stores pointer-free hot values as raw bytes; the
		// unsafe memcpy is zero-transformation and filepath builds the per-cache dir.
		imports[`"path/filepath"`] = ""
		imports[`"unsafe"`] = ""
	}
	for _, table := range tables {
		for _, field := range table.Fields {
			switch {
			case strings.Contains(field.Type, "time."):
				imports[`"time"`] = ""
			case strings.Contains(field.Type, "common."):
				imports[`"github.com/ethereum/go-ethereum/common"`] = ""
			case strings.Contains(field.Type, "uint256."):
				imports[`"github.com/holiman/uint256"`] = ""
			case strings.Contains(field.Type, "decimal."):
				imports[`"github.com/shopspring/decimal"`] = ""
			case strings.Contains(field.Type, "protomath."):
				imports[`"github.com/franz101/sqd-go/drafts/protomath"`] = ""
			}
		}
	}
	// Event views (ProtoEventBlock) reference the uint256 hot-state helpers for any
	// event with a uint256/uint256[] arg, even when no custom/hot-state table uses
	// uint256 — so the import must follow event usage too.
	if eventsUseUint256(events) || eventsUseUint256Slice(events) {
		imports[`"github.com/holiman/uint256"`] = ""
	}
	b.WriteString("import (\n")
	for _, imp := range sortedImportKeys(imports) {
		b.WriteString("\t")
		b.WriteString(imp)
		b.WriteString("\n")
	}
	b.WriteString(")\n\n")
}

func renderHotStateEntity(b *bytes.Buffer, table customTableSpec) {
	b.WriteString("type ")
	b.WriteString(table.GoTypeName)
	b.WriteString(" struct {\n")
	for _, field := range table.Fields {
		b.WriteString("\t")
		b.WriteString(field.Name)
		b.WriteString(" ")
		b.WriteString(memoryGoType(field, table.IsEvent))
		b.WriteString(" `ch:")
		b.WriteString(strconv.Quote("name=" + field.ColumnName + ";type=" + field.ColumnType))
		b.WriteString("`\n")
	}
	b.WriteString("\tTombstone bool `ch:\"-\"`\n")
	b.WriteString("}\n\n")
}

func renderClockKey(b *bytes.Buffer, spec hotStateSpec) {
	keyFields := spec.table.keyFields()
	b.WriteString("type ")
	b.WriteString(spec.keyType)
	b.WriteString(" struct {\n")
	for _, field := range keyFields {
		b.WriteString("\t")
		b.WriteString(field.Name)
		b.WriteString(" ")
		b.WriteString(field.Type)
		b.WriteString("\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("func New")
	b.WriteString(spec.keyType)
	b.WriteString("(value ")
	b.WriteString(spec.table.GoTypeName)
	b.WriteString(") ")
	b.WriteString(spec.keyType)
	b.WriteString(" {\n\treturn ")
	b.WriteString(spec.keyType)
	b.WriteString("{")
	for i, field := range keyFields {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(field.Name)
		b.WriteString(": value.")
		b.WriteString(field.Name)
	}
	b.WriteString("}\n}\n\n")
}

func renderClockCache(b *bytes.Buffer, spec hotStateSpec) {
	valueType := spec.table.GoTypeName
	keyFields := spec.table.keyFields()

	b.WriteString("type ")
	b.WriteString(spec.entryType)
	b.WriteString(" struct {\n\tkey ")
	b.WriteString(spec.keyType)
	b.WriteString("\n\tvalue ")
	b.WriteString(valueType)
	b.WriteString("\n\treferenced uint32\n\tinUse uint32\n}\n\n")

	// Cache struct. The index is a pointer-free chained hash over an arena (A3):
	// buckets[h] = ring index of a chain head (-1 = empty); next[ringIdx] = next
	// ring index in the same bucket (-1 = end). Replaces a sync.Map[key]idx whose
	// boxed key+idx interfaces were ~3 GC-scanned objects per live entry. Single
	// writer (one processor goroutine) => the index needs no locking; the CLOCK
	// entry flags stay atomic so concurrent readers (if ever reintroduced) still see
	// torn-free flag transitions.
	fmt.Fprintf(b, `type %[1]s struct {
	buckets  []int32
	next     []int32
	ring     []%[2]s
	mask     uint32
	capacity uint64
	hand     uint64
	size     uint64
	// evictions counts entries overwritten by CLOCK replacement. While zero,
	// the hot ring still holds everything ever Set — so under an authoritative
	// (from-genesis) run, hot contents are a superset of the entity's
	// ClickHouse rows and a hot miss proves a database miss.
	evictions uint64
	// cold is an optional Pebble-backed tier holding evicted entries (raw bytes).
	// nil unless attached via HotState.EnableColdCache (pointer-free entities only).
	cold *coldcache.Store
}

// Evictions reports how many entries CLOCK replacement has overwritten.
func (c *%[1]s) Evictions() uint64 {
	return atomic.LoadUint64(&c.evictions)
}

func New%[1]s(capacity uint64) *%[1]s {
	if capacity == 0 {
		capacity = DefaultClockCacheCapacity
	}
	bucketCount := uint64(8)
	for bucketCount < capacity*2 {
		bucketCount <<= 1
	}
	c := &%[1]s{
		ring:     make([]%[2]s, capacity),
		buckets:  make([]int32, bucketCount),
		next:     make([]int32, capacity),
		mask:     uint32(bucketCount - 1),
		capacity: capacity,
	}
	for i := range c.buckets {
		c.buckets[i] = -1
	}
	for i := range c.next {
		c.next[i] = -1
	}
	return c
}

`, spec.cacheType, spec.entryType)

	// keyHash folds every key field's bytes (all keys are common.Hash/Address byte
	// arrays) into a bucket index.
	fmt.Fprintf(b, "func (c *%s) keyHash(key %s) uint32 {\n\th := uint64(1469598103934665603)\n", spec.cacheType, spec.keyType)
	for _, field := range keyFields {
		fmt.Fprintf(b, "\th = clockHash64(h, key.%s[:])\n", field.Name)
	}
	b.WriteString("\treturn uint32(h^(h>>32)) & c.mask\n}\n\n")

	fmt.Fprintf(b, `func (c *%[1]s) idxLookup(key %[2]s) (uint64, bool) {
	for i := c.buckets[c.keyHash(key)]; i >= 0; i = c.next[i] {
		if c.ring[i].key == key {
			return uint64(i), true
		}
	}
	return 0, false
}

func (c *%[1]s) idxInsert(key %[2]s, ringIdx uint32) {
	h := c.keyHash(key)
	c.next[ringIdx] = c.buckets[h]
	c.buckets[h] = int32(ringIdx)
}

func (c *%[1]s) idxUnlink(key %[2]s) {
	h := c.keyHash(key)
	prev := int32(-1)
	for i := c.buckets[h]; i >= 0; i = c.next[i] {
		if c.ring[i].key == key {
			if prev < 0 {
				c.buckets[h] = c.next[i]
			} else {
				c.next[prev] = c.next[i]
			}
			c.next[i] = -1
			return
		}
		prev = i
	}
}

`, spec.cacheType, spec.keyType)

	coldOn := entityUsesCold(spec.table)
	// spill: on CLOCK eviction, write the victim (value or tombstone) to the cold
	// tier BEFORE overwriting it, so a later re-reference is served from disk and a
	// dirty-but-evicted entry isn't lost before Commit reads it.
	spill := ""
	if coldOn {
		spill = "\t\t\tif c.cold != nil {\n" +
			"\t\t\t\tc.cold.Put(unsafe.Slice((*byte)(unsafe.Pointer(&e.key)), unsafe.Sizeof(e.key)), unsafe.Slice((*byte)(unsafe.Pointer(&e.value)), unsafe.Sizeof(e.value)))\n" +
			"\t\t\t}\n"
	}
	fmt.Fprintf(b, `func (c *%[1]s) Set(value %[3]s) {
	c.SetByKey(New%[2]s(value), value)
}

func (c *%[1]s) SetByKey(key %[2]s, value %[3]s) {
	if idx, ok := c.idxLookup(key); ok {
		e := &c.ring[idx]
		if atomic.LoadUint32(&e.inUse) == 1 && e.key == key {
			e.value = value
			atomic.StoreUint32(&e.referenced, 1)
			return
		}
	}
	for {
		hand := atomic.AddUint64(&c.hand, 1)
		idx := (hand - 1) %% c.capacity
		e := &c.ring[idx]
		if atomic.CompareAndSwapUint32(&e.inUse, 1, 0) {
			if atomic.LoadUint32(&e.referenced) == 1 {
				atomic.StoreUint32(&e.referenced, 0)
				atomic.StoreUint32(&e.inUse, 1)
				continue
			}
%[4]s			atomic.AddUint64(&c.evictions, 1)
			c.idxUnlink(e.key)
			e.key = key
			e.value = value
			atomic.StoreUint32(&e.referenced, 0)
			c.idxInsert(key, uint32(idx))
			atomic.StoreUint32(&e.inUse, 1)
			return
		}
		if atomic.LoadUint32(&e.inUse) == 0 {
			if atomic.CompareAndSwapUint32(&e.inUse, 0, 2) {
				e.key = key
				e.value = value
				atomic.StoreUint32(&e.referenced, 0)
				c.idxInsert(key, uint32(idx))
				atomic.AddUint64(&c.size, 1)
				atomic.StoreUint32(&e.inUse, 1)
				return
			}
		}
	}
}

`, spec.cacheType, spec.keyType, valueType, spill)

	if coldOn {
		// Cold-consult on hot miss: an evicted entry (spilled on eviction) is served
		// from Pebble (~8µs) instead of a ClickHouse round-trip (~1.9ms), then
		// promoted back into the hot ring. A cold tombstone round-trips as a value
		// with Tombstone=true, which the state-level Get treats as "absent".
		fmt.Fprintf(b, `func (c *%[1]s) Get(key %[2]s) (%[3]s, bool) {
	if idx, ok := c.idxLookup(key); ok {
		e := &c.ring[idx]
		if atomic.LoadUint32(&e.inUse) == 1 && e.key == key {
			atomic.StoreUint32(&e.referenced, 1)
			return e.value, true
		}
	}
	if c.cold != nil {
		if vb, found, _ := c.cold.Get(unsafe.Slice((*byte)(unsafe.Pointer(&key)), unsafe.Sizeof(key))); found {
			var v %[3]s
			copy(unsafe.Slice((*byte)(unsafe.Pointer(&v)), unsafe.Sizeof(v)), vb)
			c.SetByKey(key, v)
			return v, true
		}
	}
	return %[3]s{}, false
}

`, spec.cacheType, spec.keyType, valueType)
	} else {
		fmt.Fprintf(b, `func (c *%[1]s) Get(key %[2]s) (%[3]s, bool) {
	idx, ok := c.idxLookup(key)
	if !ok {
		return %[3]s{}, false
	}
	e := &c.ring[idx]
	if atomic.LoadUint32(&e.inUse) == 1 && e.key == key {
		atomic.StoreUint32(&e.referenced, 1)
		return e.value, true
	}
	return %[3]s{}, false
}

`, spec.cacheType, spec.keyType, valueType)
	}

	if len(keyFields) > 0 {
		b.WriteString("func (c *")
		b.WriteString(spec.cacheType)
		b.WriteString(") GetByFields(")
		renderClockKeyParams(b, keyFields)
		b.WriteString(") (")
		b.WriteString(valueType)
		b.WriteString(", bool) {\n\treturn c.Get(")
		b.WriteString(spec.keyType)
		b.WriteString("{")
		for i, field := range keyFields {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(field.Name)
			b.WriteString(": ")
			b.WriteString(lowerFirst(field.Name))
		}
		b.WriteString("})\n}\n\n")
	}

	// coldDel mirrors a hard delete into the cold tier so a rolled-back key cannot
	// resurrect from disk on a later miss.
	coldDel := ""
	if coldOn {
		coldDel = "\t\t\tif c.cold != nil {\n" +
			"\t\t\t\tc.cold.Delete(unsafe.Slice((*byte)(unsafe.Pointer(&key)), unsafe.Sizeof(key)))\n" +
			"\t\t\t}\n"
	}
	fmt.Fprintf(b, `func (c *%[1]s) Delete(key %[2]s) bool {
	idx, ok := c.idxLookup(key)
	if !ok {
		return false
	}
	e := &c.ring[idx]
	if atomic.CompareAndSwapUint32(&e.inUse, 1, 0) {
		if e.key == key {
			c.idxUnlink(key)
%[4]s			e.key = %[2]s{}
			e.value = %[3]s{}
			atomic.StoreUint32(&e.referenced, 0)
			atomic.AddUint64(&c.size, ^uint64(0))
			return true
		}
		atomic.StoreUint32(&e.inUse, 1)
	}
	return false
}

func (c *%[1]s) Range(fn func(%[2]s, %[3]s) bool) {
	if fn == nil {
		return
	}
	limit := atomic.LoadUint64(&c.hand)
	if limit > c.capacity {
		limit = c.capacity
	}
	for i := uint64(0); i < limit; i++ {
		e := &c.ring[i]
		if atomic.LoadUint32(&e.inUse) == 1 {
			if !fn(e.key, e.value) {
				return
			}
		}
	}
}

func (c *%[1]s) AppendValues(dst []%[3]s) []%[3]s {
	if c == nil {
		return dst
	}
	if atomic.LoadUint64(&c.size) == 0 {
		return dst
	}
	limit := atomic.LoadUint64(&c.hand)
	if limit > c.capacity {
		limit = c.capacity
	}
	for i := 0; i < int(limit); i++ {
		e := &c.ring[i]
		if atomic.LoadUint32(&e.inUse) == 1 {
			dst = append(dst, e.value)
		}
	}
	return dst
}

func (c *%[1]s) Len() uint64 {
	return atomic.LoadUint64(&c.size)
}

`, spec.cacheType, spec.keyType, valueType, coldDel)
}

func renderCustomBatch(b *bytes.Buffer, spec hotStateSpec) {
	b.WriteString("type ")
	b.WriteString(spec.batchType)
	b.WriteString(" struct {\n")
	for _, field := range spec.table.Fields {
		b.WriteString("\t")
		b.WriteString(batchColumnField(field))
		b.WriteString(" ")
		b.WriteString(batchColumnType(field))
		b.WriteString("\n")
		if scratch := batchScratchField(field); scratch != "" {
			b.WriteString("\t")
			b.WriteString(scratch)
			b.WriteString(" ")
			b.WriteString(batchScratchType(field))
			b.WriteString("\n")
		}
	}
	b.WriteString("\tinput proto.Input\n}\n\n")

	b.WriteString("func New")
	b.WriteString(spec.batchType)
	b.WriteString("() *")
	b.WriteString(spec.batchType)
	b.WriteString(" {\n\tb := &")
	b.WriteString(spec.batchType)
	b.WriteString("{}\n")
	for _, field := range spec.table.Fields {
		for _, line := range batchInitLines(field) {
			b.WriteString("\t")
			b.WriteString(line)
			b.WriteString("\n")
		}
	}
	b.WriteString("\tb.input = proto.Input{\n")
	for _, field := range spec.table.Fields {
		b.WriteString("\t\t{Name: ")
		b.WriteString(strconv.Quote(field.ColumnName))
		b.WriteString(", Data: ")
		b.WriteString(batchInputData(field))
		b.WriteString("},\n")
	}
	b.WriteString("\t}\n\treturn b\n}\n\n")

	b.WriteString("func (b *")
	b.WriteString(spec.batchType)
	b.WriteString(") TableName() string { return ")
	b.WriteString(strconv.Quote(spec.table.Name))
	b.WriteString(" }\n\n")

	b.WriteString("func (b *")
	b.WriteString(spec.batchType)
	b.WriteString(") Rows() int { return ")
	b.WriteString(batchColumnRowsExpr(spec.table.Fields[0]))
	b.WriteString(" }\n\n")

	b.WriteString("func (b *")
	b.WriteString(spec.batchType)
	b.WriteString(") Reset() { b.input.Reset() }\n\n")

	b.WriteString("func (b *")
	b.WriteString(spec.batchType)
	b.WriteString(") Append(item ")
	b.WriteString(spec.table.GoTypeName)
	b.WriteString(") {\n")
	for _, field := range spec.table.Fields {
		for _, line := range batchAppendLines(field, spec.table.IsEvent) {
			b.WriteString("\t")
			b.WriteString(line)
			b.WriteString("\n")
		}
	}
	b.WriteString("}\n\n")

	b.WriteString("func (b *")
	b.WriteString(spec.batchType)
	b.WriteString(") Inputs() proto.Input { return b.input }\n\n")

	b.WriteString("func (b *")
	b.WriteString(spec.batchType)
	b.WriteString(") Insert(ctx context.Context, conn *ch.Client, db string) error {\n\tif b.Rows() == 0 {\n\t\treturn nil\n\t}\n\treturn conn.Do(ctx, ch.Query{Body: fmt.Sprintf(")
	b.WriteString(strconv.Quote("INSERT INTO %s.%s " + customInsertColumnList(spec.table) + " VALUES"))
	// wait_for_async_insert is 0 (fire-and-forget) so a Commit with N dirty tables
	// issues N pipelined inserts without blocking on each table's server-side flush
	// (each block on the async busy-timeout was the dominant backfill cost). The
	// read-back invariant the old wait=1 protected — recovery/rollback/resolver
	// SELECTs must see committed rows — is instead upheld by HotState.Commit, which
	// issues ONE "SYSTEM FLUSH ASYNC INSERT QUEUE" barrier (under s.mu) after the
	// inserts and before returning, draining every buffer. Same durability, one
	// flush per commit instead of one wait per table: ~2.3x faster end-to-end.
	b.WriteString(", quoteIdent(db), quoteIdent(b.TableName())), Input: b.input, Settings: []ch.Setting{{Key: \"async_insert\", Value: \"1\", Important: true}, {Key: \"wait_for_async_insert\", Value: \"0\", Important: true}}})\n}\n\n")
}

func renderClockRecover(b *bytes.Buffer, spec hotStateSpec) {
	b.WriteString("func (c *")
	b.WriteString(spec.cacheType)
	b.WriteString(") Recover(ctx context.Context, conn *ch.Client, db string) error {\n\tvar (\n")
	for _, field := range spec.table.Fields {
		b.WriteString("\t\t")
		b.WriteString(batchColumnField(field))
		b.WriteString(" ")
		b.WriteString(resultColumnType(field))
		b.WriteString("\n")
	}
	b.WriteString("\t)\n")
	for _, field := range spec.table.Fields {
		for _, line := range resultInitLines(field) {
			b.WriteString("\t")
			b.WriteString(line)
			b.WriteString("\n")
		}
	}
	b.WriteString("\tresults := proto.Results{\n")
	for _, field := range spec.table.Fields {
		b.WriteString("\t\t{Name: ")
		b.WriteString(strconv.Quote(field.ColumnName))
		b.WriteString(", Data: ")
		b.WriteString(resultData(field))
		b.WriteString("},\n")
	}
	b.WriteString("\t}\n")
	b.WriteString("\treturn conn.Do(ctx, ch.Query{Body: fmt.Sprintf(")
	b.WriteString(strconv.Quote(recoverQuery(spec.table)))
	b.WriteString(", quoteIdent(db), quoteIdent(")
	b.WriteString(strconv.Quote(spec.table.Name))
	b.WriteString(")), Result: results, OnResult: func(ctx context.Context, block proto.Block) error {\n\t\tfor i := 0; i < block.Rows; i++ {\n\t\t\titem := ")
	b.WriteString(spec.table.GoTypeName)
	b.WriteString("{\n")
	for _, field := range spec.table.Fields {
		b.WriteString("\t\t\t\t")
		b.WriteString(field.Name)
		b.WriteString(": ")
		b.WriteString(resultValueExpr(field, spec.table.IsEvent))
		b.WriteString(",\n")
	}
	b.WriteString("\t\t\t}\n\t\t\tc.Set(item)\n\t\t}\n\t\treturn nil\n\t}})\n}\n\n")
}

func renderHotStateType(b *bytes.Buffer, specs []hotStateSpec) {
	b.WriteString("type HotState struct {\n")
	for _, spec := range specs {
		resolverType := spec.table.GoTypeName + "BatchResolver"
		b.WriteString("\t")
		b.WriteString(spec.baseName)
		b.WriteString(" *")
		b.WriteString(spec.cacheType)
		b.WriteString("\n")

		b.WriteString("\t")
		b.WriteString(spec.baseName)
		b.WriteString("Resolver *")
		b.WriteString(resolverType)
		b.WriteString("\n")

		if !spec.table.IsEvent {
			b.WriteString("\tdirty")
			b.WriteString(spec.baseName)
			b.WriteString(" map[")
			b.WriteString(spec.keyType)
			b.WriteString("]struct{}\n")
		}
	}
	b.WriteString("\tmu sync.Mutex\n")
	b.WriteString("\t// coldAuthoritative is set when hot∪cold provably covers every persisted\n")
	b.WriteString("\t// state row: either the cold tier was opened against an empty ClickHouse\n")
	b.WriteString("\t// (from-genesis backfill), or a full rebuild-from-ClickHouse just streamed\n")
	b.WriteString("\t// every state table through the caches with the cold tier attached. A\n")
	b.WriteString("\t// hot+cold miss is then provably new, so the lazy state Get skips the\n")
	b.WriteString("\t// ClickHouse point-SELECT entirely.\n")
	b.WriteString("\tcoldAuthoritative bool\n")
	b.WriteString("\t// coldDir / coldCacheBytes / coldMemTableBytes remember the EnableColdCache\n")
	b.WriteString("\t// configuration so the tier can be re-opened fresh on a rebuild.\n")
	b.WriteString("\tcoldDir           string\n")
	b.WriteString("\tcoldCacheBytes    int64\n")
	b.WriteString("\tcoldMemTableBytes uint64\n")
	b.WriteString("}\n\n")

	b.WriteString("func NewHotState(capacity uint64) *HotState {\n\tif capacity == 0 {\n\t\tcapacity = DefaultClockCacheCapacity\n\t}\n")
	b.WriteString("\tstate := &HotState{\n")
	for _, spec := range specs {
		b.WriteString("\t\t")
		b.WriteString(spec.baseName)
		b.WriteString(": New")
		b.WriteString(spec.cacheType)
		b.WriteString("(capacity),\n")
		if !spec.table.IsEvent {
			b.WriteString("\t\tdirty")
			b.WriteString(spec.baseName)
			b.WriteString(": make(map[")
			b.WriteString(spec.keyType)
			b.WriteString("]struct{}),\n")
		}
	}
	b.WriteString("\t}\n")
	for _, spec := range specs {
		resolverType := spec.table.GoTypeName + "BatchResolver"
		b.WriteString("\tstate.")
		b.WriteString(spec.baseName)
		b.WriteString("Resolver = New")
		b.WriteString(resolverType)
		b.WriteString("(state.")
		b.WriteString(spec.baseName)
		b.WriteString(")\n")
	}
	b.WriteString("\treturn state\n}\n\n")

	// EnableColdCache / CloseColdCache: attach the Pebble cold tier to every
	// pointer-free entity. authoritative=true (from-genesis, empty ClickHouse) lets
	// the lazy Get skip ClickHouse on a hot+cold miss. Default-off — callers that
	// never enable it get byte-for-byte the prior behaviour.
	var coldSpecs []hotStateSpec
	for _, spec := range specs {
		if entityUsesCold(spec.table) {
			coldSpecs = append(coldSpecs, spec)
		}
	}
	b.WriteString("// ColdAuthoritative reports whether the cold tier is authoritative for misses\n")
	b.WriteString("// (opened against an empty ClickHouse): a hot+cold miss is provably new, so\n")
	b.WriteString("// callers batching their own resolver round-trips may skip them entirely.\n")
	b.WriteString("func (s *HotState) ColdAuthoritative() bool {\n\treturn s != nil && s.coldAuthoritative\n}\n\n")
	if len(coldSpecs) == 0 {
		b.WriteString("func (s *HotState) EnableColdCache(dir string, authoritative bool, cacheBytes int64, memTableBytes uint64) error {\n\treturn nil\n}\n\n")
		b.WriteString("func (s *HotState) ReopenColdCacheFresh() (bool, error) {\n\treturn false, nil\n}\n\n")
		b.WriteString("func (s *HotState) CloseColdCache() error {\n\treturn nil\n}\n\n")
	} else {
		b.WriteString("func (s *HotState) EnableColdCache(dir string, authoritative bool, cacheBytes int64, memTableBytes uint64) error {\n")
		b.WriteString("\tif s == nil {\n\t\treturn nil\n\t}\n")
		b.WriteString("\tvar err error\n")
		for _, spec := range coldSpecs {
			b.WriteString("\tif s.")
			b.WriteString(spec.baseName)
			b.WriteString(".cold, err = coldcache.Open(filepath.Join(dir, ")
			b.WriteString(strconv.Quote(spec.baseName))
			b.WriteString("), cacheBytes, memTableBytes); err != nil {\n\t\treturn err\n\t}\n")
		}
		b.WriteString("\ts.coldAuthoritative = authoritative\n")
		b.WriteString("\ts.coldDir = dir\n")
		b.WriteString("\ts.coldCacheBytes = cacheBytes\n")
		b.WriteString("\ts.coldMemTableBytes = memTableBytes\n")
		b.WriteString("\treturn nil\n}\n\n")

		b.WriteString("// ReopenColdCacheFresh closes and re-opens the cold tier at its configured\n")
		b.WriteString("// directory (coldcache.Open wipes the dir, so any entries from before a\n")
		b.WriteString("// rollback are discarded). Authoritative stays false until the caller proves\n")
		b.WriteString("// coverage. Reports whether a cold tier is configured; no-op without one.\n")
		b.WriteString("func (s *HotState) ReopenColdCacheFresh() (bool, error) {\n")
		b.WriteString("\tif s == nil || s.coldDir == \"\" {\n\t\treturn false, nil\n\t}\n")
		b.WriteString("\tdir, cacheBytes, memTableBytes := s.coldDir, s.coldCacheBytes, s.coldMemTableBytes\n")
		b.WriteString("\t_ = s.CloseColdCache()\n")
		b.WriteString("\tif err := s.EnableColdCache(dir, false, cacheBytes, memTableBytes); err != nil {\n\t\treturn false, err\n\t}\n")
		b.WriteString("\treturn true, nil\n}\n\n")

		b.WriteString("func (s *HotState) CloseColdCache() error {\n")
		b.WriteString("\tif s == nil {\n\t\treturn nil\n\t}\n")
		b.WriteString("\tvar firstErr error\n")
		for _, spec := range coldSpecs {
			b.WriteString("\tif s.")
			b.WriteString(spec.baseName)
			b.WriteString(".cold != nil {\n\t\tif e := s.")
			b.WriteString(spec.baseName)
			b.WriteString(".cold.Close(); e != nil && firstErr == nil {\n\t\t\tfirstErr = e\n\t\t}\n\t\ts.")
			b.WriteString(spec.baseName)
			b.WriteString(".cold = nil\n\t}\n")
		}
		b.WriteString("\ts.coldAuthoritative = false\n")
		b.WriteString("\treturn firstErr\n}\n\n")
	}

	b.WriteString("func (s *HotState) Recover(ctx context.Context, conn *ch.Client, db string) error {\n")
	for _, spec := range specs {
		if spec.table.IsEvent {
			continue
		}
		b.WriteString("\tif err := s.")
		b.WriteString(spec.baseName)
		b.WriteString(".Recover(ctx, conn, db); err != nil {\n\t\treturn err\n\t}\n")
	}
	b.WriteString("\treturn nil\n}\n\n")

	// Generate Update methods
	for _, spec := range specs {
		if spec.table.IsEvent {
			continue
		}
		b.WriteString("func (s *HotState) Update")
		b.WriteString(spec.table.GoTypeName)
		b.WriteString("(value ")
		b.WriteString(spec.table.GoTypeName)
		b.WriteString(") {\n")
		b.WriteString("\ts.mu.Lock()\n")
		b.WriteString("\tdefer s.mu.Unlock()\n")
		b.WriteString("\ts.")
		b.WriteString(spec.baseName)
		b.WriteString(".Set(value)\n")
		b.WriteString("\ts.dirty")
		b.WriteString(spec.baseName)
		b.WriteString("[New")
		b.WriteString(spec.keyType)
		b.WriteString("(value)] = struct{}{}\n")
		b.WriteString("}\n\n")
	}

	// Generate Commit method
	b.WriteString("func (s *HotState) Commit(ctx context.Context, conn *ch.Client, db string) error {\n")
	b.WriteString("\ts.mu.Lock()\n")
	b.WriteString("\tdefer s.mu.Unlock()\n")
	b.WriteString("\tif conn == nil {\n")
	for _, spec := range specs {
		if spec.table.IsEvent {
			continue
		}
		b.WriteString("\t\tclear(s.dirty")
		b.WriteString(spec.baseName)
		b.WriteString(")\n")
	}
	b.WriteString("\t\treturn nil\n")
	b.WriteString("\t}\n")
	// hadWork: true if any non-event table is dirty this commit. Gates the single
	// async-flush barrier below so an empty commit issues no server round-trip.
	b.WriteString("\thadWork := ")
	hadWorkFirst := true
	for _, spec := range specs {
		if spec.table.IsEvent {
			continue
		}
		if !hadWorkFirst {
			b.WriteString(" || ")
		}
		b.WriteString("len(s.dirty")
		b.WriteString(spec.baseName)
		b.WriteString(") > 0")
		hadWorkFirst = false
	}
	if hadWorkFirst {
		b.WriteString("false")
	}
	b.WriteString("\n")
	for _, spec := range specs {
		if spec.table.IsEvent {
			continue
		}
		b.WriteString("\tif len(s.dirty")
		b.WriteString(spec.baseName)
		b.WriteString(") > 0 {\n")
		b.WriteString("\t\tbatch := New")
		b.WriteString(spec.batchType)
		b.WriteString("()\n")
		b.WriteString("\t\tfor key := range s.dirty")
		b.WriteString(spec.baseName)
		b.WriteString(" {\n")
		b.WriteString("\t\t\tif val, ok := s.")
		b.WriteString(spec.baseName)
		b.WriteString(".Get(key); ok {\n")
		b.WriteString("\t\t\t\tbatch.Append(val)\n")
		b.WriteString("\t\t\t}\n")
		b.WriteString("\t\t}\n")
		b.WriteString("\t\tif err := batch.Insert(ctx, conn, db); err != nil {\n")
		b.WriteString("\t\t\treturn err\n")
		b.WriteString("\t\t}\n")
		b.WriteString("\t\tclear(s.dirty")
		b.WriteString(spec.baseName)
		b.WriteString(")\n")
		b.WriteString("\t}\n")
	}
	// Single async-flush barrier: the per-table inserts above are
	// wait_for_async_insert=0, so this one server flush makes all of them durable
	// and queryable before Commit returns (still under s.mu), preserving the
	// recovery/rollback/resolver read-back invariant at one flush per commit
	// instead of one wait per table insert.
	b.WriteString("\tif hadWork {\n")
	b.WriteString("\t\tif err := conn.Do(ctx, ch.Query{Body: \"SYSTEM FLUSH ASYNC INSERT QUEUE\"}); err != nil {\n")
	b.WriteString("\t\t\treturn err\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn nil\n}\n")

		// Generate Restore methods for journal rollback
		for _, spec := range specs {
			if spec.table.IsEvent {
				continue
			}
			b.WriteString("func (s *HotState) Restore")
			b.WriteString(spec.table.GoTypeName)
			b.WriteString("(key ")
			b.WriteString(spec.keyType)
			b.WriteString(", value ")
			b.WriteString(spec.table.GoTypeName)
			b.WriteString(", had bool) {\n")
			b.WriteString("\ts.mu.Lock()\n")
			b.WriteString("\tdefer s.mu.Unlock()\n")
			b.WriteString("\tif had {\n")
			b.WriteString("\t\ts.")
			b.WriteString(spec.baseName)
			b.WriteString(".SetByKey(key, value)\n")
			b.WriteString("\t\ts.dirty")
			b.WriteString(spec.baseName)
			b.WriteString("[key] = struct{}{}\n")
			b.WriteString("\t\treturn\n")
			b.WriteString("\t}\n")
			b.WriteString("\ts.")
			b.WriteString(spec.baseName)
			b.WriteString(".Delete(key)\n")
			b.WriteString("\tdelete(s.dirty")
			b.WriteString(spec.baseName)
			b.WriteString(", key)\n")
			b.WriteString("}\n\n")
		}
}

func renderHotStateHelpers(b *bytes.Buffer, tables []customTableSpec, events []eventSpec) {
	// Shared FNV-1a byte fold used by every clock cache's flat index (A3). The
	// index is a pointer-free open-chained hash over an arena (buckets []int32 head
	// + next []int32 chain), so the GC scans two flat integer slices instead of the
	// millions of boxed interface objects a sync.Map[key]idx allocated.
	b.WriteString(`
func clockHash64(seed uint64, b []byte) uint64 {
	h := seed
	for _, x := range b {
		h ^= uint64(x)
		h *= 1099511628211
	}
	return h
}
`)
	if customTablesUseBool(tables) {
		b.WriteString("\nfunc hotStateBool(v bool) uint8 {\n\tif v {\n\t\treturn 1\n\t}\n\treturn 0\n}\n")
		b.WriteString("\nfunc hotStateBoolSQL(v bool) string {\n\tif v {\n\t\treturn \"1\"\n\t}\n\treturn \"0\"\n}\n")
	}
	if customTablesUseUint256(tables) || customTablesUseUint256Slice(tables) ||
		eventsUseUint256(events) || eventsUseUint256Slice(events) {
		b.WriteString(`
func hotStateUInt256(v uint256.Int) proto.UInt256 {
	return proto.UInt256{
		Low:  proto.UInt128{Low: v[0], High: v[1]},
		High: proto.UInt128{Low: v[2], High: v[3]},
	}
}

func hotStateUint256(v proto.UInt256) uint256.Int {
	return uint256.Int{v.Low.Low, v.Low.High, v.High.Low, v.High.High}
}
`)
	}
	if customTablesUseDecimal(tables) {
		b.WriteString(`
func hotStateDecimalToDecimal256(d decimal.Decimal) protomath.Decimal256 {
	out, _ := protomath.FromDecimal256ScaledBigInt(d.Shift(18).BigInt())
	return out
}

func hotStateDecimalFromDecimal256(v protomath.Decimal256) decimal.Decimal {
	return decimal.NewFromBigInt(v.ScaledBig(), -18)
}
`)
	}
	if customTablesUseType(tables, "protomath.Decimal256") {
		b.WriteString(`
type decimal256Col struct {
	proto.ColDecimal256
}

func (c *decimal256Col) Type() proto.ColumnType {
	return proto.ColumnType("Decimal(76, 18)")
}
`)
	}
	if customTablesUseHashSlice(tables) {
		b.WriteString(`
func hotStateHashSliceBytes(values []common.Hash, scratch [][]byte) [][]byte {
	scratch = scratch[:0]
	for _, value := range values {
		scratch = append(scratch, value.Bytes())
	}
	return scratch
}

func hotStateHashSlice(values [][]byte) []common.Hash {
	out := make([]common.Hash, 0, len(values))
	for _, value := range values {
		out = append(out, common.BytesToHash(value))
	}
	return out
}
`)
	}
	if customTablesUseUint256Slice(tables) || eventsUseUint256Slice(events) {
		b.WriteString(`
func hotStateUInt256Slice(values []uint256.Int, scratch []proto.UInt256) []proto.UInt256 {
	scratch = scratch[:0]
	for _, value := range values {
		scratch = append(scratch, hotStateUInt256(value))
	}
	return scratch
}

func hotStateUint256Slice(values []proto.UInt256) []uint256.Int {
	out := make([]uint256.Int, 0, len(values))
	for _, value := range values {
		out = append(out, hotStateUint256(value))
	}
	return out
}
`)
	}
}

