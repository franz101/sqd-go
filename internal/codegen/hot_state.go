func generateHotStateGo(tables []customTableSpec, events []eventSpec) ([]byte, error) {
	var b bytes.Buffer
	specs := hotStateSpecs(tables)

	b.WriteString(`// Code generated by sqd-go codegen; DO NOT EDIT.

package generated

`)
	renderHotStateImports(&b, tables, events)

	b.WriteString("const DefaultClockCacheCapacity uint64 = 100000\n")
	b.WriteString("const recoveryBucketCount = 8\n")
	// recoveryConcurrency bounds how many bucket queries run at once during
	// Recover. Beyond ~8 the latest-per-key scan is decompression-bound, so 8
	// saturates a typical box without extra connections.
	b.WriteString("const recoveryConcurrency = 8\n\n")
	if customTablesUseSerializedCold(tables) {
		b.WriteString("// coldBoolByte packs a bool for the cold-tier value codec.\n")
		b.WriteString("func coldBoolByte(x bool) byte {\n\tif x {\n\t\treturn 1\n\t}\n\treturn 0\n}\n\n")
	}
	b.WriteString(`func recoveryFixedStringRange(column string, bucket int, size int) string {
	if recoveryBucketCount <= 1 {
		return "1"
	}
	width := 256 / recoveryBucketCount
	lower := bucket * width
	lowerHex := fmt.Sprintf("%02x%s", lower, strings.Repeat("00", size-1))
	lowerExpr := fmt.Sprintf("toFixedString(unhex('%s'), %d)", lowerHex, size)
	if bucket >= recoveryBucketCount-1 {
		return fmt.Sprintf("%s >= %s", column, lowerExpr)
	}
	upper := (bucket + 1) * width
	upperHex := fmt.Sprintf("%02x%s", upper, strings.Repeat("00", size-1))
	upperExpr := fmt.Sprintf("toFixedString(unhex('%s'), %d)", upperHex, size)
	return fmt.Sprintf("%s >= %s AND %s < %s", column, lowerExpr, column, upperExpr)
}

func recoveryDialConn(ctx context.Context) (*ch.Client, error) {
	host := os.Getenv("CLICKHOUSE_HOST")
	if host == "" {
		host = "127.0.0.1"
	}
	port := 9000
	if v := os.Getenv("CLICKHOUSE_NATIVE_PORT"); v != "" {
		if p, err := strconv.Atoi(v); err == nil {
			port = p
		}
	}
	user := os.Getenv("CLICKHOUSE_USER")
	if user == "" {
		user = "default"
	}
	return ch.Dial(ctx, ch.Options{
		Address:  fmt.Sprintf("%s:%d", host, port),
		Database: "default",
		User:     user,
		Password: os.Getenv("CLICKHOUSE_PASSWORD"),
	})
}

// recoverBucketsParallel runs the latest-per-key scan for nbuckets disjoint
// key-prefix buckets concurrently, then applies every decoded row on a single
// goroutine. Each worker owns its own ch.Client (ch-go connections are not safe
// for concurrent Do): the pool is the caller's primary connection plus up to
// recoveryConcurrency-1 freshly dialed ones, and a dial failure just means fewer
// workers rather than an error. run executes one bucket against a connection and
// hands each decoded block to flush; set applies one row to the cache. The cache
// and its cold tier are not safe for concurrent writers, so the queries fan out
// while every set runs on the lone consumer. Buckets partition the keyspace, so
// no key is ever set twice and set ordering is irrelevant.
func recoverBucketsParallel[T any](
	ctx context.Context,
	primary *ch.Client,
	nbuckets int,
	run func(ctx context.Context, conn *ch.Client, bucket int, flush func([]T)) error,
	set func(T),
) error {
	if nbuckets <= 1 {
		return run(ctx, primary, 0, func(batch []T) {
			for i := range batch {
				set(batch[i])
			}
		})
	}

	conc := recoveryConcurrency
	if conc > nbuckets {
		conc = nbuckets
	}
	conns := make([]*ch.Client, 1, conc)
	conns[0] = primary
	for len(conns) < conc {
		wc, err := recoveryDialConn(ctx)
		if err != nil {
			break
		}
		conns = append(conns, wc)
	}
	defer func() {
		for _, wc := range conns[1:] {
			_ = wc.Close()
		}
	}()

	ctx, cancel := context.WithCancel(ctx)
	defer cancel()

	items := make(chan []T, len(conns)*2)
	var consumerWG sync.WaitGroup
	consumerWG.Add(1)
	go func() {
		defer consumerWG.Done()
		for batch := range items {
			for i := range batch {
				set(batch[i])
			}
		}
	}()

	buckets := make(chan int)
	var (
		workerWG sync.WaitGroup
		errMu    sync.Mutex
		firstErr error
	)
	fail := func(err error) {
		if err == nil {
			return
		}
		errMu.Lock()
		if firstErr == nil {
			firstErr = err
			cancel()
		}
		errMu.Unlock()
	}
	flush := func(batch []T) {
		if len(batch) == 0 {
			return
		}
		select {
		case items <- batch:
		case <-ctx.Done():
		}
	}
	for _, conn := range conns {
		workerWG.Add(1)
		go func(conn *ch.Client) {
			defer workerWG.Done()
			for bucket := range buckets {
				if err := run(ctx, conn, bucket, flush); err != nil {
					fail(err)
					return
				}
			}
		}(conn)
	}
feed:
	for bucket := 0; bucket < nbuckets; bucket++ {
		select {
		case buckets <- bucket:
		case <-ctx.Done():
			break feed
		}
	}
	close(buckets)
	workerWG.Wait()
	close(items)
	consumerWG.Wait()
	return firstErr
}

`)
	for _, spec := range specs {
		if !spec.table.IsEvent {
			renderHotStateEntity(&b, spec.table)
		}
		renderClockKey(&b, spec)
		renderClockCache(&b, spec)
		if !spec.table.IsEvent {
			renderCustomBatch(&b, spec)
			renderClockRecover(&b, spec)
		}
		renderBatchResolver(&b, spec)
	}
	renderHotStateType(&b, specs)
	renderHotStateHelpers(&b, tables, events)

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format source: %w", err)
	}
	return formatted, nil
}

func renderHotStateImports(b *bytes.Buffer, tables []customTableSpec, events []eventSpec) {
	imports := map[string]string{
		`"context"`:                           "",
		`"fmt"`:                               "",
		`"os"`:                                "",
		`"strconv"`:                           "",
		`"strings"`:                           "",
		`"sync"`:                              "",
		`"sync/atomic"`:                       "",
		`"github.com/ClickHouse/ch-go"`:       "",
		`"github.com/ClickHouse/ch-go/proto"`: "",
		`"github.com/franz101/sqd-go/internal/coldcache"`: "",
	}
	if customTablesUseDecimal(tables) {
		imports[`"encoding/binary"`] = ""
		imports[`"math/big"`] = ""
	}
	if customTablesUseColdCache(tables) {
		// Cold tier (Pebble) stores pointer-free hot values as raw bytes; the
		// unsafe memcpy is zero-transformation and filepath builds the per-cache dir.
		imports[`"path/filepath"`] = ""
		imports[`"unsafe"`] = ""
	}
	if customTablesUseSerializedCold(tables) {
		// Slice-bearing entities spill to / load from the cold tier via the
		// generated byte codec, which packs scalars little-endian.
		imports[`"encoding/binary"`] = ""
		// math.Float*bits only appears in the codec for float-valued cold fields.
		for _, table := range tables {
			if !entityUsesSerializedCold(table) {
				continue
			}
			for _, field := range table.Fields {
				if t := memoryGoType(field, table.IsEvent); t == "float32" || t == "float64" {
					imports[`"math"`] = ""
				}
			}
		}
	}
	for _, table := range tables {
		for _, field := range table.Fields {
			switch {
			case strings.Contains(field.Type, "time."):
				imports[`"time"`] = ""
			case strings.Contains(field.Type, "common."):
				imports[`"github.com/ethereum/go-ethereum/common"`] = ""
			case strings.Contains(field.Type, "uint256."):
				imports[`"github.com/holiman/uint256"`] = ""
			case strings.Contains(field.Type, "decimal."):
				imports[`"github.com/shopspring/decimal"`] = ""
			case strings.Contains(field.Type, "protomath."):
				imports[`"github.com/franz101/sqd-go/drafts/protomath"`] = ""
			}
		}
	}
	// Event views (ProtoEventBlock) reference the uint256 hot-state helpers for any
	// event with a uint256/uint256[] arg, even when no custom/hot-state table uses
	// uint256 — so the import must follow event usage too.
	if eventsUseUint256(events) || eventsUseUint256Slice(events) {
		imports[`"github.com/holiman/uint256"`] = ""
	}
	b.WriteString("import (\n")
	for _, imp := range sortedImportKeys(imports) {
		b.WriteString("\t")
		b.WriteString(imp)
		b.WriteString("\n")
	}
	b.WriteString(")\n\n")
}

func renderHotStateEntity(b *bytes.Buffer, table customTableSpec) {
	b.WriteString("type ")
	b.WriteString(table.GoTypeName)
	b.WriteString(" struct {\n")
	for _, field := range table.Fields {
		b.WriteString("\t")
		b.WriteString(field.Name)
		b.WriteString(" ")
		b.WriteString(memoryGoType(field, table.IsEvent))
		b.WriteString(" `ch:")
		b.WriteString(strconv.Quote("name=" + field.ColumnName + ";type=" + field.ColumnType))
		b.WriteString("`\n")
	}
	b.WriteString("\tTombstone bool `ch:\"-\"`\n")
	b.WriteString("}\n\n")
}

func renderClockKey(b *bytes.Buffer, spec hotStateSpec) {
	keyFields := spec.table.keyFields()
	b.WriteString("type ")
	b.WriteString(spec.keyType)
	b.WriteString(" struct {\n")
	for _, field := range keyFields {
		b.WriteString("\t")
		b.WriteString(field.Name)
		b.WriteString(" ")
		b.WriteString(field.Type)
		b.WriteString("\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("func New")
	b.WriteString(spec.keyType)
	b.WriteString("(value ")
	b.WriteString(spec.table.GoTypeName)
	b.WriteString(") ")
	b.WriteString(spec.keyType)
	b.WriteString(" {\n\treturn ")
	b.WriteString(spec.keyType)
	b.WriteString("{")
	for i, field := range keyFields {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(field.Name)
		b.WriteString(": value.")
		b.WriteString(field.Name)
	}
	b.WriteString("}\n}\n\n")
}

func renderClockCache(b *bytes.Buffer, spec hotStateSpec) {
	valueType := spec.table.GoTypeName
	keyFields := spec.table.keyFields()

	b.WriteString("type ")
	b.WriteString(spec.entryType)
	b.WriteString(" struct {\n\tkey ")
	b.WriteString(spec.keyType)
	b.WriteString("\n\tvalue ")
	b.WriteString(valueType)
	b.WriteString("\n\treferenced uint32\n\tinUse uint32\n}\n\n")

	// Cache struct. The index is a pointer-free chained hash over an arena (A3):
	// buckets[h] = ring index of a chain head (-1 = empty); next[ringIdx] = next
	// ring index in the same bucket (-1 = end). Replaces a sync.Map[key]idx whose
	// boxed key+idx interfaces were ~3 GC-scanned objects per live entry. Single
	// writer (one processor goroutine) => the index needs no locking; the CLOCK
	// entry flags stay atomic so concurrent readers (if ever reintroduced) still see
	// torn-free flag transitions.
	fmt.Fprintf(b, `type %[1]s struct {
	buckets  []int32
	next     []int32
	ring     []%[2]s
	mask     uint32
	capacity uint64
	hand     uint64
	size     uint64
	// evictions counts entries overwritten by CLOCK replacement. While zero,
	// the hot ring still holds everything ever Set — so under an authoritative
	// (from-genesis) run, hot contents are a superset of the entity's
	// ClickHouse rows and a hot miss proves a database miss.
	evictions uint64
	// cold is an optional Pebble-backed tier holding evicted entries (raw bytes).
	// nil unless attached via HotState.EnableColdCache (pointer-free entities only).
	cold *coldcache.Store
}

// Evictions reports how many entries CLOCK replacement has overwritten.
func (c *%[1]s) Evictions() uint64 {
	return atomic.LoadUint64(&c.evictions)
}

func New%[1]s(capacity uint64) *%[1]s {
	if capacity == 0 {
		capacity = DefaultClockCacheCapacity
	}
	bucketCount := uint64(8)
	for bucketCount < capacity*2 {
		bucketCount <<= 1
	}
	c := &%[1]s{
		ring:     make([]%[2]s, capacity),
		buckets:  make([]int32, bucketCount),
		next:     make([]int32, capacity),
		mask:     uint32(bucketCount - 1),
		capacity: capacity,
	}
	for i := range c.buckets {
		c.buckets[i] = -1
	}
	for i := range c.next {
		c.next[i] = -1
	}
	return c
}

`, spec.cacheType, spec.entryType)

	// keyHash folds every key field's bytes (all keys are common.Hash/Address byte
	// arrays) into a bucket index.
	fmt.Fprintf(b, "func (c *%s) keyHash(key %s) uint32 {\n\th := uint64(1469598103934665603)\n", spec.cacheType, spec.keyType)
	for _, field := range keyFields {
		fmt.Fprintf(b, "\th = clockHash64(h, key.%s[:])\n", field.Name)
	}
	b.WriteString("\treturn uint32(h^(h>>32)) & c.mask\n}\n\n")

	fmt.Fprintf(b, `func (c *%[1]s) idxLookup(key %[2]s) (uint64, bool) {
	for i := c.buckets[c.keyHash(key)]; i >= 0; i = c.next[i] {
		if c.ring[i].key == key {
			return uint64(i), true
		}
	}
	return 0, false
}

func (c *%[1]s) idxInsert(key %[2]s, ringIdx uint32) {
	h := c.keyHash(key)
	c.next[ringIdx] = c.buckets[h]
	c.buckets[h] = int32(ringIdx)
}

func (c *%[1]s) idxUnlink(key %[2]s) {
	h := c.keyHash(key)
	prev := int32(-1)
	for i := c.buckets[h]; i >= 0; i = c.next[i] {
		if c.ring[i].key == key {
			if prev < 0 {
				c.buckets[h] = c.next[i]
			} else {
				c.next[prev] = c.next[i]
			}
			c.next[i] = -1
			return
		}
		prev = i
	}
}

`, spec.cacheType, spec.keyType)

	coldOn := entityUsesCold(spec.table)
	serializedCold := entityUsesSerializedCold(spec.table)
	// spill: on CLOCK eviction, write the victim (value or tombstone) to the cold
	// tier BEFORE overwriting it, so a later re-reference is served from disk and a
	// dirty-but-evicted entry isn't lost before Commit reads it. Pointer-free values
	// blit as raw struct bytes; slice-bearing values go through the byte codec.
	spill := ""
	if coldOn {
		valuePut := "unsafe.Slice((*byte)(unsafe.Pointer(&e.value)), unsafe.Sizeof(e.value))"
		if serializedCold {
			valuePut = "coldEncode" + valueType + "(&e.value)"
		}
		spill = "\t\t\tif c.cold != nil {\n" +
			"\t\t\t\tc.cold.Put(unsafe.Slice((*byte)(unsafe.Pointer(&e.key)), unsafe.Sizeof(e.key)), " + valuePut + ")\n" +
			"\t\t\t}\n"
	}
	fmt.Fprintf(b, `func (c *%[1]s) Set(value %[3]s) {
	c.SetByKey(New%[2]s(value), value)
}

func (c *%[1]s) SetByKey(key %[2]s, value %[3]s) {
	if idx, ok := c.idxLookup(key); ok {
		e := &c.ring[idx]
		if atomic.LoadUint32(&e.inUse) == 1 && e.key == key {
			e.value = value
			atomic.StoreUint32(&e.referenced, 1)
			return
		}
	}
	for {
		hand := atomic.AddUint64(&c.hand, 1)
		idx := (hand - 1) %% c.capacity
		e := &c.ring[idx]
		if atomic.CompareAndSwapUint32(&e.inUse, 1, 0) {
			if atomic.LoadUint32(&e.referenced) == 1 {
				atomic.StoreUint32(&e.referenced, 0)
				atomic.StoreUint32(&e.inUse, 1)
				continue
			}
%[4]s			atomic.AddUint64(&c.evictions, 1)
			c.idxUnlink(e.key)
			e.key = key
			e.value = value
			atomic.StoreUint32(&e.referenced, 0)
			c.idxInsert(key, uint32(idx))
			atomic.StoreUint32(&e.inUse, 1)
			return
		}
		if atomic.LoadUint32(&e.inUse) == 0 {
			if atomic.CompareAndSwapUint32(&e.inUse, 0, 2) {
				e.key = key
				e.value = value
				atomic.StoreUint32(&e.referenced, 0)
				c.idxInsert(key, uint32(idx))
				atomic.AddUint64(&c.size, 1)
				atomic.StoreUint32(&e.inUse, 1)
				return
			}
		}
	}
}

`, spec.cacheType, spec.keyType, valueType, spill)

	if coldOn && serializedCold {
		// Cold-consult on hot miss, byte-codec variant: the slice-bearing value is
		// decoded from the Pebble bytes, then promoted back into the hot ring. A cold
		// tombstone round-trips as a value with Tombstone=true (state Get treats it as
		// "absent"). Serving from disk (~8µs) replaces the ClickHouse SELECT (~1.9ms).
		fmt.Fprintf(b, `func (c *%[1]s) Get(key %[2]s) (%[3]s, bool) {
	if idx, ok := c.idxLookup(key); ok {
		e := &c.ring[idx]
		if atomic.LoadUint32(&e.inUse) == 1 && e.key == key {
			atomic.StoreUint32(&e.referenced, 1)
			return e.value, true
		}
	}
	if c.cold != nil {
		if raw, found, _ := c.cold.Get(unsafe.Slice((*byte)(unsafe.Pointer(&key)), unsafe.Sizeof(key))); found {
			v := coldDecode%[3]s(raw)
			c.SetByKey(key, v)
			return v, true
		}
	}
	return %[3]s{}, false
}

`, spec.cacheType, spec.keyType, valueType)
	} else if coldOn {
		// Cold-consult on hot miss: an evicted entry (spilled on eviction) is served
		// from Pebble (~8µs) instead of a ClickHouse round-trip (~1.9ms), then
		// promoted back into the hot ring. A cold tombstone round-trips as a value
		// with Tombstone=true, which the state-level Get treats as "absent".
		fmt.Fprintf(b, `func (c *%[1]s) Get(key %[2]s) (%[3]s, bool) {
	if idx, ok := c.idxLookup(key); ok {
		e := &c.ring[idx]
		if atomic.LoadUint32(&e.inUse) == 1 && e.key == key {
			atomic.StoreUint32(&e.referenced, 1)
			return e.value, true
		}
	}
	if c.cold != nil {
		var v %[3]s
		if found, _ := c.cold.GetInto(unsafe.Slice((*byte)(unsafe.Pointer(&v)), unsafe.Sizeof(v)), unsafe.Slice((*byte)(unsafe.Pointer(&key)), unsafe.Sizeof(key))); found {
			c.SetByKey(key, v)
			return v, true
		}
	}
	return %[3]s{}, false
}

`, spec.cacheType, spec.keyType, valueType)
	} else {
		fmt.Fprintf(b, `func (c *%[1]s) Get(key %[2]s) (%[3]s, bool) {
	idx, ok := c.idxLookup(key)
	if !ok {
		return %[3]s{}, false
	}
	e := &c.ring[idx]
	if atomic.LoadUint32(&e.inUse) == 1 && e.key == key {
		atomic.StoreUint32(&e.referenced, 1)
		return e.value, true
	}
	return %[3]s{}, false
}

`, spec.cacheType, spec.keyType, valueType)
	}

	if len(keyFields) > 0 {
		b.WriteString("func (c *")
		b.WriteString(spec.cacheType)
		b.WriteString(") GetByFields(")
		renderClockKeyParams(b, keyFields)
		b.WriteString(") (")
		b.WriteString(valueType)
		b.WriteString(", bool) {\n\treturn c.Get(")
		b.WriteString(spec.keyType)
		b.WriteString("{")
		for i, field := range keyFields {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(field.Name)
			b.WriteString(": ")
			b.WriteString(lowerFirst(field.Name))
		}
		b.WriteString("})\n}\n\n")
	}

	// coldDel mirrors a hard delete into the cold tier so a rolled-back key cannot
	// resurrect from disk on a later miss.
	coldDel := ""
	if coldOn {
		coldDel = "\t\t\tif c.cold != nil {\n" +
			"\t\t\t\tc.cold.Delete(unsafe.Slice((*byte)(unsafe.Pointer(&key)), unsafe.Sizeof(key)))\n" +
			"\t\t\t}\n"
	}
	fmt.Fprintf(b, `func (c *%[1]s) Delete(key %[2]s) bool {
	idx, ok := c.idxLookup(key)
	if !ok {
		return false
	}
	e := &c.ring[idx]
	if atomic.CompareAndSwapUint32(&e.inUse, 1, 0) {
		if e.key == key {
			c.idxUnlink(key)
%[4]s			e.key = %[2]s{}
			e.value = %[3]s{}
			atomic.StoreUint32(&e.referenced, 0)
			atomic.AddUint64(&c.size, ^uint64(0))
			return true
		}
		atomic.StoreUint32(&e.inUse, 1)
	}
	return false
}

func (c *%[1]s) Range(fn func(%[2]s, %[3]s) bool) {
	if fn == nil {
		return
	}
	limit := atomic.LoadUint64(&c.hand)
	if limit > c.capacity {
		limit = c.capacity
	}
	for i := uint64(0); i < limit; i++ {
		e := &c.ring[i]
		if atomic.LoadUint32(&e.inUse) == 1 {
			if !fn(e.key, e.value) {
				return
			}
		}
	}
}

func (c *%[1]s) AppendValues(dst []%[3]s) []%[3]s {
	if c == nil {
		return dst
	}
	if atomic.LoadUint64(&c.size) == 0 {
		return dst
	}
	limit := atomic.LoadUint64(&c.hand)
	if limit > c.capacity {
		limit = c.capacity
	}
	for i := 0; i < int(limit); i++ {
		e := &c.ring[i]
		if atomic.LoadUint32(&e.inUse) == 1 {
			dst = append(dst, e.value)
		}
	}
	return dst
}

func (c *%[1]s) Len() uint64 {
	return atomic.LoadUint64(&c.size)
}

`, spec.cacheType, spec.keyType, valueType, coldDel)

	if serializedCold {
		renderColdValueCodec(b, spec)
	}
}

// renderColdValueCodec emits coldEncode<Type>/coldDecode<Type> for a slice-bearing
// cold entity: a compact, self-describing byte image of the in-memory value struct
// (every field in declaration order, plus the runtime Tombstone flag). Scalars are
// little-endian; slices are uint32-count-prefixed. The format must round-trip the
// exact in-memory representation (memoryGoType: time.Time -> int64), since the cold
// tier is the authoritative overflow store, not a re-derivable cache.
func renderColdValueCodec(b *bytes.Buffer, spec hotStateSpec) {
	valueType := spec.table.GoTypeName
	fields := append([]customFieldSpec{}, spec.table.Fields...)
	fields = append(fields, customFieldSpec{Name: "Tombstone", Type: "bool"})

	fmt.Fprintf(b, "func coldEncode%[1]s(v *%[1]s) []byte {\n\tb := make([]byte, 0, %d)\n", valueType, coldEncodeHint(fields))
	for _, f := range fields {
		b.WriteString(coldEncodeField(f))
	}
	b.WriteString("\treturn b\n}\n\n")

	fmt.Fprintf(b, "func coldDecode%[1]s(p []byte) %[1]s {\n\tvar v %[1]s\n\toff := 0\n", valueType)
	for _, f := range fields {
		b.WriteString(coldDecodeField(f))
	}
	b.WriteString("\t_ = off\n\treturn v\n}\n\n")
}

// coldEncodeHint pre-sizes the encode buffer to the sum of the fixed-width fields
// (slices grow it as needed); purely an allocation hint.
func coldEncodeHint(fields []customFieldSpec) int {
	n := 0
	for _, f := range fields {
		switch memoryGoType(f, false) {
		case "common.Hash", "uint256.Int":
			n += 32
		case "common.Address":
			n += 20
		case "protomath.Decimal256":
			n += 32
		case "bool", "uint8", "int8":
			n += 1
		case "uint16", "int16":
			n += 2
		case "uint32", "int32", "float32":
			n += 4
		case "uint", "uint64", "int", "int64", "float64":
			n += 8
		default:
			n += 8 // slices / variable: count prefix
		}
	}
	return n
}

// coldEncodeField returns the encode statement(s) for one value-struct field.
// Panics at codegen time on an unsupported type rather than emitting a value that
// silently fails to round-trip.
func coldEncodeField(f customFieldSpec) string {
	v := "v." + f.Name
	switch memoryGoType(f, false) {
	case "common.Hash", "common.Address":
		return "\tb = append(b, " + v + "[:]...)\n"
	case "uint256.Int":
		return "\t{\n\t\tbs := " + v + ".Bytes32()\n\t\tb = append(b, bs[:]...)\n\t}\n"
	case "protomath.Decimal256":
		return "\t{\n\t\tbs := " + v + ".Bytes32()\n\t\tb = append(b, bs[:]...)\n\t}\n"
	case "bool":
		return "\tb = append(b, coldBoolByte(" + v + "))\n"
	case "uint8":
		return "\tb = append(b, " + v + ")\n"
	case "int8":
		return "\tb = append(b, byte(" + v + "))\n"
	case "uint16":
		return "\tb = binary.LittleEndian.AppendUint16(b, " + v + ")\n"
	case "int16":
		return "\tb = binary.LittleEndian.AppendUint16(b, uint16(" + v + "))\n"
	case "uint32":
		return "\tb = binary.LittleEndian.AppendUint32(b, " + v + ")\n"
	case "int32":
		return "\tb = binary.LittleEndian.AppendUint32(b, uint32(" + v + "))\n"
	case "float32":
		return "\tb = binary.LittleEndian.AppendUint32(b, math.Float32bits(" + v + "))\n"
	case "uint", "uint64":
		return "\tb = binary.LittleEndian.AppendUint64(b, uint64(" + v + "))\n"
	case "int", "int64":
		return "\tb = binary.LittleEndian.AppendUint64(b, uint64(" + v + "))\n"
	case "float64":
		return "\tb = binary.LittleEndian.AppendUint64(b, math.Float64bits(" + v + "))\n"
	case "[]uint256.Int":
		return "\tb = binary.LittleEndian.AppendUint32(b, uint32(len(" + v + ")))\n" +
			"\tfor i := range " + v + " {\n\t\tbs := " + v + "[i].Bytes32()\n\t\tb = append(b, bs[:]...)\n\t}\n"
	case "[]common.Hash":
		return "\tb = binary.LittleEndian.AppendUint32(b, uint32(len(" + v + ")))\n" +
			"\tfor i := range " + v + " {\n\t\tb = append(b, " + v + "[i][:]...)\n\t}\n"
	case "[]common.Address":
		return "\tb = binary.LittleEndian.AppendUint32(b, uint32(len(" + v + ")))\n" +
			"\tfor i := range " + v + " {\n\t\tb = append(b, " + v + "[i][:]...)\n\t}\n"
	default:
		panic(fmt.Sprintf("coldEncodeField: unsupported cold-tier field type %q for %s; add a codec case", memoryGoType(f, false), f.Name))
	}
}

// coldDecodeField returns the decode statement(s) for one value-struct field,
// advancing the running offset `off`.
func coldDecodeField(f customFieldSpec) string {
	v := "v." + f.Name
	switch memoryGoType(f, false) {
	case "common.Hash":
		return "\tcopy(" + v + "[:], p[off:off+32])\n\toff += 32\n"
	case "common.Address":
		return "\tcopy(" + v + "[:], p[off:off+20])\n\toff += 20\n"
	case "uint256.Int", "protomath.Decimal256":
		return "\t" + v + ".SetBytes(p[off : off+32])\n\toff += 32\n"
	case "bool":
		return "\t" + v + " = p[off] != 0\n\toff++\n"
	case "uint8":
		return "\t" + v + " = p[off]\n\toff++\n"
	case "int8":
		return "\t" + v + " = int8(p[off])\n\toff++\n"
	case "uint16":
		return "\t" + v + " = binary.LittleEndian.Uint16(p[off : off+2])\n\toff += 2\n"
	case "int16":
		return "\t" + v + " = int16(binary.LittleEndian.Uint16(p[off : off+2]))\n\toff += 2\n"
	case "uint32":
		return "\t" + v + " = binary.LittleEndian.Uint32(p[off : off+4])\n\toff += 4\n"
	case "int32":
		return "\t" + v + " = int32(binary.LittleEndian.Uint32(p[off : off+4]))\n\toff += 4\n"
	case "float32":
		return "\t" + v + " = math.Float32frombits(binary.LittleEndian.Uint32(p[off : off+4]))\n\toff += 4\n"
	case "uint", "uint64":
		return "\t" + v + " = binary.LittleEndian.Uint64(p[off : off+8])\n\toff += 8\n"
	case "int", "int64":
		return "\t" + v + " = int64(binary.LittleEndian.Uint64(p[off : off+8]))\n\toff += 8\n"
	case "float64":
		return "\t" + v + " = math.Float64frombits(binary.LittleEndian.Uint64(p[off : off+8]))\n\toff += 8\n"
	case "[]uint256.Int":
		return "\t{\n\t\tn := int(binary.LittleEndian.Uint32(p[off : off+4]))\n\t\toff += 4\n" +
			"\t\tif n > 0 {\n\t\t\t" + v + " = make([]uint256.Int, n)\n" +
			"\t\t\tfor i := 0; i < n; i++ {\n\t\t\t\t" + v + "[i].SetBytes(p[off : off+32])\n\t\t\t\toff += 32\n\t\t\t}\n\t\t}\n\t}\n"
	case "[]common.Hash":
		return "\t{\n\t\tn := int(binary.LittleEndian.Uint32(p[off : off+4]))\n\t\toff += 4\n" +
			"\t\tif n > 0 {\n\t\t\t" + v + " = make([]common.Hash, n)\n" +
			"\t\t\tfor i := 0; i < n; i++ {\n\t\t\t\tcopy(" + v + "[i][:], p[off:off+32])\n\t\t\t\toff += 32\n\t\t\t}\n\t\t}\n\t}\n"
	case "[]common.Address":
		return "\t{\n\t\tn := int(binary.LittleEndian.Uint32(p[off : off+4]))\n\t\toff += 4\n" +
			"\t\tif n > 0 {\n\t\t\t" + v + " = make([]common.Address, n)\n" +
			"\t\t\tfor i := 0; i < n; i++ {\n\t\t\t\tcopy(" + v + "[i][:], p[off:off+20])\n\t\t\t\toff += 20\n\t\t\t}\n\t\t}\n\t}\n"
	default:
		panic(fmt.Sprintf("coldDecodeField: unsupported cold-tier field type %q for %s; add a codec case", memoryGoType(f, false), f.Name))
	}
}

