// isPointerFreeEntity reports whether the entity's in-memory value AND key are
// free of pointers/slices/strings, so they can be stored in the Pebble cold tier
// as raw bytes via unsafe memcpy (zero-transformation). Slice-bearing entities
// (e.g. Array(UInt256) payouts, Array(FixedString(32)) question_ids) are excluded
// and keep the ClickHouse-fallback lazy-load path. Note: memoryGoType maps
// time.Time -> int64 for non-event entities, so timestamps don't disqualify them.
func isPointerFreeEntity(table customTableSpec) bool {
	notFlat := func(t string) bool {
		return strings.HasPrefix(t, "[]") || strings.HasPrefix(t, "*") ||
			strings.HasPrefix(t, "map[") || strings.Contains(t, "string") ||
			t == "time.Time"
	}
	for _, field := range table.Fields {
		if notFlat(memoryGoType(field, table.IsEvent)) {
			return false
		}
	}
	for _, field := range table.keyFields() {
		if notFlat(field.Type) {
			return false
		}
	}
	return true
}

// entityUsesCold reports whether a (non-event) entity participates in the Pebble
// cold tier. Events are append-only (no lazy Get-by-key), so they never need it.
// Every derived state entity does: pointer-free values are spilled/served as raw
// bytes (unsafe memcpy), slice-bearing values via the generated byte codec
// (entityUsesSerializedCold). Keeping slice-bearing entities (e.g. Condition's
// []uint256.Int payouts) OUT of the cold tier was the root of the resumed-run
// ClickHouse point-SELECT storm: once their hot ring evicted, every miss fell
// back to a synchronous CH lookup with no disk tier to absorb it.
func entityUsesCold(table customTableSpec) bool {
	return !table.IsEvent
}

// entityUsesSerializedCold reports whether a cold entity must use the generated
// byte codec (encode/decode) rather than the zero-copy unsafe memcpy: true when
// its in-memory value carries a slice/pointer field that can't be blitted as raw
// struct bytes. The KEY stays fixed-size (pointer-free) in both cases, so the
// cold lookup key is always an unsafe slice of the key struct.
func entityUsesSerializedCold(table customTableSpec) bool {
	return entityUsesCold(table) && !isPointerFreeEntity(table)
}

// customTablesUseColdCache reports whether any entity can use the cold tier;
// drives the "unsafe" + "path/filepath" imports in the generated hot state.
func customTablesUseColdCache(tables []customTableSpec) bool {
	for _, table := range tables {
		if entityUsesCold(table) {
			return true
		}
	}
	return false
}

// customTablesUseSerializedCold reports whether any cold entity needs the byte
// codec (drives the "encoding/binary" import and the shared codec helpers).
func customTablesUseSerializedCold(tables []customTableSpec) bool {
	for _, table := range tables {
		if entityUsesSerializedCold(table) {
			return true
		}
	}
	return false
}

func renderBatchResolver(b *bytes.Buffer, spec hotStateSpec) {
	resolverType := spec.table.GoTypeName + "BatchResolver"
	cacheType := spec.cacheType
	keyType := spec.keyType
	valueType := spec.table.GoTypeName

	b.WriteString("type ")
	b.WriteString(resolverType)
	b.WriteString(" struct {\n\tcache  *")
	b.WriteString(cacheType)
	b.WriteString("\n\tmisses []")
	b.WriteString(keyType)
	b.WriteString("\n}\n\n")

	b.WriteString("func New")
	b.WriteString(resolverType)
	b.WriteString("(cache *")
	b.WriteString(cacheType)
	b.WriteString(") *")
	b.WriteString(resolverType)
	b.WriteString(" {\n\treturn &")
	b.WriteString(resolverType)
	b.WriteString("{\n\t\tcache: cache,\n\t}\n}\n\n")

	b.WriteString("func (r *")
	b.WriteString(resolverType)
	b.WriteString(") Queue(key ")
	b.WriteString(keyType)
	b.WriteString(") {\n\tif _, ok := r.cache.Get(key); !ok {\n\t\tr.misses = append(r.misses, key)\n\t}\n}\n\n")

	b.WriteString("// Pending reports how many missed keys are queued for the next Resolve.\n")
	b.WriteString("func (r *")
	b.WriteString(resolverType)
	b.WriteString(") Pending() int {\n\treturn len(r.misses)\n}\n\n")

	b.WriteString("func (r *")
	b.WriteString(resolverType)
	b.WriteString(") Resolve(ctx context.Context, conn *ch.Client, db string) error {\n")
	b.WriteString("\tif len(r.misses) == 0 {\n\t\treturn nil\n\t}\n\n")
	b.WriteString("\tuniqueKeys := make(map[")
	b.WriteString(keyType)
	b.WriteString("]struct{})\n")
	b.WriteString("\tvar uniqueList []")
	b.WriteString(keyType)
	b.WriteString("\n\tfor _, key := range r.misses {\n")
	b.WriteString("\t\tif _, ok := uniqueKeys[key]; !ok {\n")
	b.WriteString("\t\t\tuniqueKeys[key] = struct{}{}\n")
	b.WriteString("\t\t\tuniqueList = append(uniqueList, key)\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
	b.WriteString("\tr.misses = nil\n\n")
	b.WriteString("\tif len(uniqueList) == 0 {\n\t\treturn nil\n\t}\n\n")
	b.WriteString("\tfoundKeys := make(map[")
	b.WriteString(keyType)
	b.WriteString("]struct{})\n")
	b.WriteString("\tconst resolverChunkSize = 4000\n")
	b.WriteString("\tfor chunkStart := 0; chunkStart < len(uniqueList); chunkStart += resolverChunkSize {\n")
	b.WriteString("\t\tchunkEnd := chunkStart + resolverChunkSize\n")
	b.WriteString("\t\tif chunkEnd > len(uniqueList) {\n\t\t\tchunkEnd = len(uniqueList)\n\t\t}\n")
	b.WriteString("\t\tchunk := uniqueList[chunkStart:chunkEnd]\n\n")

	keyFields := spec.table.keyFields()
	if len(keyFields) > 1 && keyFieldsExternalFixed(keyFields) {
		for _, field := range keyFields {
			colName := "keyCol" + field.Name
			size := 32
			if field.Type == "common.Address" {
				size = 20
			}
			b.WriteString("\t\tvar ")
			b.WriteString(colName)
			b.WriteString(" proto.ColFixedStr\n")
			b.WriteString("\t\t")
			b.WriteString(colName)
			b.WriteString(".SetSize(")
			b.WriteString(strconv.Itoa(size))
			b.WriteString(")\n")
		}
		b.WriteString("\t\tfor _, key := range chunk {\n")
		for _, field := range keyFields {
			b.WriteString("\t\t\tkeyCol")
			b.WriteString(field.Name)
			b.WriteString(".Append(key.")
			b.WriteString(field.Name)
			b.WriteString(".Bytes())\n")
		}
		b.WriteString("\t\t}\n\n")
		queryBody := fmt.Sprintf("SELECT %s FROM %%s.%s AS `t` INNER JOIN _resolver_keys AS `k` ON %s ORDER BY `t`.`block_number` DESC, `t`.`transaction_index` DESC, `t`.`log_index` DESC LIMIT 1 BY %s",
			customSelectColumnListQualified(spec.table, "`t`"),
			spec.table.Name,
			keyJoinCondition(keyFields, "`t`", "`k`"),
			keyColumnExpressionListQualified(keyFields, "`t`"),
		)
		b.WriteString(fmt.Sprintf("\t\tqueryStr := fmt.Sprintf(%s, quoteIdent(db))\n\n",
			strconv.Quote(queryBody),
		))
	} else if len(keyFields) > 1 {
		b.WriteString("\t\tvar values []string\n")
		b.WriteString("\t\tfor _, key := range chunk {\n")
		b.WriteString("\t\t\tvalues = append(values, \"(\"")
		for i, field := range keyFields {
			if i > 0 {
				b.WriteString(" + \", \"")
			}
			b.WriteString(" + ")
			b.WriteString(keySQLValueExpr("key."+field.Name, field))
		}
		b.WriteString(" + \")\")\n")
		b.WriteString("\t\t}\n\n")

		queryBody := fmt.Sprintf("SELECT %s FROM %%s.%s WHERE %s IN (%%s) ORDER BY `block_number` DESC, `transaction_index` DESC, `log_index` DESC LIMIT 1 BY %s",
			customSelectColumnList(spec.table),
			spec.table.Name,
			customInsertColumnList(customTableSpec{Columns: keyColumns(keyFields)}),
			keyColumnExpressionList(keyFields),
		)
		b.WriteString(fmt.Sprintf("\t\tqueryStr := fmt.Sprintf(%s, quoteIdent(db), strings.Join(values, \", \"))\n\n",
			strconv.Quote(queryBody),
		))
	} else if len(keyFields) == 1 {
		b.WriteString("\t\tvar values []string\n")
		b.WriteString("\t\tfor _, key := range chunk {\n")
		keyField := keyFields[0]
		b.WriteString("\t\t\tvalues = append(values, ")
		b.WriteString(keySQLValueExpr("key."+keyField.Name, keyField))
		b.WriteString(")\n")
		b.WriteString("\t\t}\n\n")

		queryBody := fmt.Sprintf("SELECT %s FROM %%s.%s WHERE %s IN (%%s) ORDER BY `block_number` DESC, `transaction_index` DESC, `log_index` DESC LIMIT 1 BY %s",
			customSelectColumnList(spec.table),
			spec.table.Name,
			quoteSQLIdent(keyField.ColumnName),
			keyColumnExpressionList(keyFields),
		)
		b.WriteString(fmt.Sprintf("\t\tqueryStr := fmt.Sprintf(%s, quoteIdent(db), strings.Join(values, \", \"))\n\n",
			strconv.Quote(queryBody),
		))
	} else {
		b.WriteString("\t\tqueryStr := \"\"\n")
	}

	b.WriteString("\t\tvar (\n")
	for _, field := range spec.table.Fields {
		b.WriteString("\t\t\t")
		b.WriteString(batchColumnField(field))
		b.WriteString(" ")
		b.WriteString(resultColumnType(field))
		b.WriteString("\n")
	}
	b.WriteString("\t\t)\n")
	for _, field := range spec.table.Fields {
		for _, line := range resultInitLines(field) {
			b.WriteString("\t\t")
			b.WriteString(line)
			b.WriteString("\n")
		}
	}
	b.WriteString("\t\tresults := proto.Results{\n")
	for _, field := range spec.table.Fields {
		b.WriteString("\t\t\t{Name: ")
		b.WriteString(strconv.Quote(field.ColumnName))
		b.WriteString(", Data: ")
		b.WriteString(resultData(field))
		b.WriteString("},\n")
	}
	b.WriteString("\t\t}\n")

	b.WriteString("\t\tq := ch.Query{\n")
	b.WriteString("\t\t\tBody:   queryStr,\n")
	b.WriteString("\t\t\tResult: results,\n")
	b.WriteString("\t\t\tSettings: []ch.Setting{{Key: \"max_query_size\", Value: \"10485760\"}},\n")
	if len(keyFields) > 1 && keyFieldsExternalFixed(keyFields) {
		b.WriteString("\t\t\tExternalTable: \"_resolver_keys\",\n")
		b.WriteString("\t\t\tExternalData: []proto.InputColumn{\n")
		for _, field := range keyFields {
			b.WriteString("\t\t\t\t{Name: ")
			b.WriteString(strconv.Quote(field.ColumnName))
			b.WriteString(", Data: keyCol")
			b.WriteString(field.Name)
			b.WriteString("},\n")
		}
		b.WriteString("\t\t\t},\n")
	}
	b.WriteString("\t\t\tOnResult: func(ctx context.Context, block proto.Block) error {\n")
	b.WriteString("\t\t\t\tfor i := 0; i < block.Rows; i++ {\n")
	b.WriteString("\t\t\t\t\titem := ")
	b.WriteString(valueType)
	b.WriteString("{\n")
	if spec.table.IsEvent {
		b.WriteString("\t\t\t\t\t\tEventMeta: EventMeta{\n")
		for _, field := range spec.table.Fields {
			if field.Name == "BlockNumber" || field.Name == "BlockTimestamp" || field.Name == "TransactionIndex" || field.Name == "LogIndex" {
				b.WriteString("\t\t\t\t\t\t\t")
				b.WriteString(field.Name)
				b.WriteString(": ")
				b.WriteString(resultValueExpr(field, spec.table.IsEvent))
				b.WriteString(",\n")
			}
		}
		b.WriteString("\t\t\t\t\t\t},\n")
		for _, field := range spec.table.Fields {
			if !(field.Name == "BlockNumber" || field.Name == "BlockTimestamp" || field.Name == "TransactionIndex" || field.Name == "LogIndex") {
				b.WriteString("\t\t\t\t\t\t")
				b.WriteString(field.Name)
				b.WriteString(": ")
				b.WriteString(resultValueExpr(field, spec.table.IsEvent))
				b.WriteString(",\n")
			}
		}
	} else {
		for _, field := range spec.table.Fields {
			b.WriteString("\t\t\t\t\t\t")
			b.WriteString(field.Name)
			b.WriteString(": ")
			b.WriteString(resultValueExpr(field, spec.table.IsEvent))
			b.WriteString(",\n")
		}
	}
	b.WriteString("\t\t\t\t\t}\n")
	b.WriteString("\t\t\t\t\tr.cache.Set(item)\n")
	b.WriteString("\t\t\t\t\tfoundKeys[New")
	b.WriteString(keyType)
	b.WriteString("(item)] = struct{}{}\n")
	b.WriteString("\t\t\t\t}\n")
	b.WriteString("\t\t\t\treturn nil\n")
	b.WriteString("\t\t\t},\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t\tif err := conn.Do(ctx, q); err != nil {\n\t\t\treturn err\n\t\t}\n")
	b.WriteString("\t}\n")
	b.WriteString("\tfor _, key := range uniqueList {\n")
	b.WriteString("\t\tif _, found := foundKeys[key]; !found {\n")
	b.WriteString("\t\t\ttombstone := ")
	b.WriteString(valueType)
	b.WriteString("{Tombstone: true}\n")
	for _, field := range keyFields {
		b.WriteString("\t\t\ttombstone.")
		b.WriteString(field.Name)
		b.WriteString(" = key.")
		b.WriteString(field.Name)
		b.WriteString("\n")
	}
	b.WriteString("\t\t\tr.cache.SetByKey(key, tombstone)\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn nil\n")
	b.WriteString("}\n\n")
}

func keySQLValueExpr(expr string, field customFieldSpec) string {
	switch field.Type {
	case "common.Address", "common.Hash":
		return fmt.Sprintf("fmt.Sprintf(\"unhex('%%s')\", strings.TrimPrefix(%s.Hex(), \"0x\"))", expr)
	case "string":
		return fmt.Sprintf("fmt.Sprintf(\"'%%s'\", strings.ReplaceAll(%s, \"'\", \"''\"))", expr)
	case "bool":
		return fmt.Sprintf("hotStateBoolSQL(%s)", expr)
	case "uint256.Int":
		return expr + ".Dec()"
	case "decimal.Decimal":
		return fmt.Sprintf("fmt.Sprintf(\"'%%s'\", %s.String())", expr)
	case "protomath.Decimal256":
		return fmt.Sprintf("fmt.Sprintf(\"'%%s'\", %s.String(protomath.Decimal256Scale18))", expr)
	case "float32", "float64":
		return fmt.Sprintf("fmt.Sprintf(\"%%v\", %s)", expr)
	case "time.Time":
		return fmt.Sprintf("fmt.Sprintf(\"'%%s'\", %s.UTC().Format(time.RFC3339Nano))", expr)
	default:
		return fmt.Sprintf("fmt.Sprintf(\"%%d\", %s)", expr)
	}
}

func customSelectColumnList(table customTableSpec) string {
	selects := make([]string, 0, len(table.Fields))
	for _, field := range table.Fields {
		selects = append(selects, quoteSQLIdent(field.ColumnName))
	}
	return strings.Join(selects, ", ")
}

func customSelectColumnListQualified(table customTableSpec, alias string) string {
	selects := make([]string, 0, len(table.Fields))
	for _, field := range table.Fields {
		col := quoteSQLIdent(field.ColumnName)
		selects = append(selects, alias+"."+col+" AS "+col)
	}
	return strings.Join(selects, ", ")
}

func keyColumns(fields []customFieldSpec) []customColumnSpec {
	out := make([]customColumnSpec, 0, len(fields))
	for _, f := range fields {
		out = append(out, customColumnSpec{Name: f.ColumnName})
	}
	return out
}

func keyColumnExpressionList(fields []customFieldSpec) string {
	out := make([]string, 0, len(fields))
	for _, field := range fields {
		out = append(out, quoteSQLIdent(field.ColumnName))
	}
	return strings.Join(out, ", ")
}

func keyColumnExpressionListQualified(fields []customFieldSpec, alias string) string {
	out := make([]string, 0, len(fields))
	for _, field := range fields {
		out = append(out, alias+"."+quoteSQLIdent(field.ColumnName))
	}
	return strings.Join(out, ", ")
}

func keyJoinCondition(fields []customFieldSpec, leftAlias, rightAlias string) string {
	out := make([]string, 0, len(fields))
	for _, field := range fields {
		col := quoteSQLIdent(field.ColumnName)
		out = append(out, leftAlias+"."+col+" = "+rightAlias+"."+col)
	}
	return strings.Join(out, " AND ")
}

func keyFieldsExternalFixed(fields []customFieldSpec) bool {
	for _, field := range fields {
		if field.Type != "common.Address" && field.Type != "common.Hash" {
			return false
		}
	}
	return len(fields) > 0
}

func findStateEventSpec(events []eventSpec, state config.StateConfig) (*eventSpec, error) {
	if state.SourceTable != "" {
		for _, ev := range events {
			if ev.TableName == state.SourceTable {
				return &ev, nil
			}
		}
	}
	// Try to resolve from state.Name
	for _, ev := range events {
		if strings.EqualFold(ev.EventName, state.Name) || strings.EqualFold(ev.GoTypeName, state.Name) {
			return &ev, nil
		}
	}
	// Fallback: try to see if any event table contains the state name
	for _, ev := range events {
		if strings.Contains(strings.ToLower(ev.TableName), strings.ToLower(state.Name)) {
			return &ev, nil
		}
	}
	return nil, fmt.Errorf("source table or event matching %q not found in event tables", state.Name)
}
